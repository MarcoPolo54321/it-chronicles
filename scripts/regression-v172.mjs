import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SAVE_VERSION, createNewGame } from '../www/js/core/game.js';
import { ALL_COMPONENTS } from '../www/js/data/components.js';
import { ALL_ORDERS } from '../www/js/data/orders.js';
import { ALL_EDUCATION, ALL_JOBS } from '../www/js/data/progression.js';
import { MARKET_EVENTS_V13, ERA_VISUAL_THEMES_V13 } from '../www/js/data/v13.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
assert.ok(SAVE_VERSION>=17);
assert.ok(ALL_COMPONENTS.every(x=>Number(x.fromYear||2000)<=2010));
assert.ok(ALL_ORDERS.every(x=>Number(x.fromYear||2000)<=2010));
assert.ok(ALL_EDUCATION.every(x=>Number(x.fromYear||2000)<=2010));
assert.ok(ALL_JOBS.every(x=>Number(x.fromYear||2000)<=2010));
assert.ok(MARKET_EVENTS_V13.every(x=>Number(x.from||2000)<=2010 && Number(x.to||2010)<=2010));
assert.ok(ERA_VISUAL_THEMES_V13.every(x=>Number(x.to||2010)<=2010));
const game=createNewGame({name:'Тест',specialization:'hardware'});
assert.ok(game.version>=17);
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
assert.ok(pkg.androidVersionCode>=1702);
assert.match(pkg.version,/^0\.(?:17\.[2-9]|18\.\d+)$/);
const render=fs.readFileSync(path.join(root,'www/js/ui/render.js'),'utf8');
assert.match(render,/постоянный навык сохраняется/);
assert.doesNotMatch(render,/уменьшается постоянный уровень/);
const pngs=[];
function walk(dir){for(const ent of fs.readdirSync(dir,{withFileTypes:true})){const p=path.join(dir,ent.name);if(ent.isDirectory())walk(p);else if(p.endsWith('.png'))pngs.push(p)}}
walk(path.join(root,'www/assets/ui-v171'));
assert.equal(pngs.length,0);
console.log('Regression v0.17.2: OK');

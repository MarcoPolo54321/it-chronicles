const YEARS = [2000,2001,2003,2006,2008];
const PLAYER_LEVELS = [1,3,6,10,14];
const SKILL_LEVELS = [0,3,5,7,9];
const PROFESSION_XP = [0,120,360,720,1200];

function jobFrom(branch, row, index) {
  const tier=index+1;
  const [name,salary,desc]=row;
  const reqSkills=tier===1?{}:{[branch.id]:SKILL_LEVELS[index]};
  if(tier>=4 && branch.id!=='management') reqSkills.management=Math.max(3,tier+1);
  return {
    id:`v162_${branch.id}_${tier}`,
    branchId:branch.id,
    name,
    icon:branch.icon,
    careerTier:tier,
    salary,
    salaryGrowthPerYear:[300,500,800,1200,1800][index],
    reqLevel:PLAYER_LEVELS[index],
    reqSkills,
    professionXpRequired:PROFESSION_XP[index],
    fromYear:YEARS[index],
    toYear:2010,
    desc
  };
}

export const CAREER_BRANCHES_V162 = BRANCH_SPECS.map((branch)=>({
  ...branch,
  jobs:branch.jobs.map((row,index)=>jobFrom(branch,row,index))
}));

export const CAREER_JOBS_V162 = CAREER_BRANCHES_V162.flatMap((branch)=>branch.jobs);
export const CAREER_PROFESSION_XP_THRESHOLDS_V162 = PROFESSION_XP;

export function careerBranchById(id){return CAREER_BRANCHES_V162.find((item)=>item.id===id)||null;}
export function careerJobByBranchTier(branchId,tier){return CAREER_JOBS_V162.find((item)=>item.branchId===branchId&&item.careerTier===Number(tier))||null;}
